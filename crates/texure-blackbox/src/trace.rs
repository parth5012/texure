/// Render the single-file trace viewer HTML for one recorded run.
pub fn render_trace_html(
    run: &RunRecord,
    scenarios: &[ScenarioResultRecord],
    steps: &[StepRecord],
) -> String {
    #[derive(Serialize)]
    struct TraceDoc<'a> {
        run: &'a RunRecord,
        scenarios: &'a [ScenarioResultRecord],
        steps: &'a [StepRecord],
    }

    let doc = TraceDoc {
        run,
        scenarios,
        steps,
    };

    let pass = scenarios.iter().filter(|s| s.status == "PASS").count();
    let fail = scenarios.iter().filter(|s| s.status == "FAIL").count();
    let skip = scenarios
        .iter()
        .filter(|s| s.status == "SKIP" || s.status == "DEVICE-SKIP")
        .count();

    let mut scen_rows = String::new();
    for s in scenarios {
        let cls = status_class(&s.status);
        scen_rows.push_str("<tr><td><span class=\"chip chip-");
        scen_rows.push_str(cls);
        scen_rows.push_str("\">");
        scen_rows.push_str(&esc(&s.status));
        scen_rows.push_str("</span></td><td><code>");
        scen_rows.push_str(&esc(&s.scenario_id));
        scen_rows.push_str("</code></td><td>");
        scen_rows.push_str(&esc(&s.name));
        scen_rows.push_str("</td><td>");
        scen_rows.push_str(&s.duration_ms.to_string());
        scen_rows.push_str("ms</td>");
        if let Some(ref code) = s.error_code {
            scen_rows.push_str("<td class=\"error-banner\"><strong>");
            scen_rows.push_str(&esc(code));
            scen_rows.push_str("</strong> ");
            scen_rows.push_str(&esc(s.error_message.as_deref().unwrap_or("")));
            scen_rows.push_str("</td>");
        } else {
            scen_rows.push_str("<td></td>");
        }
        scen_rows.push_str("</tr>");
    }

    let step_max = steps.len().saturating_sub(1);

    TRACE_TEMPLATE
        .replace("__RUN_ID__", &esc(&run.run_id))
        .replace("__PASS__", &pass.to_string())
        .replace("__FAIL__", &fail.to_string())
        .replace("__SKIP__", &skip.to_string())
        .replace("__TS__", &esc(&run.timestamp))
        .replace(
            "__BRANCH__",
            &esc(run.branch.as_deref().unwrap_or("unknown")),
        )
        .replace(
            "__BUILD__",
            &esc(run.build_hash.as_deref().unwrap_or("unknown")),
        )
        .replace("__DUR__", &run.duration_ms.to_string())
        .replace("__SCENARIOS__", &scen_rows)
        .replace("__STEP_MAX__", &step_max.to_string())
        .replace("__DATA__", &embed_json(&doc))
}

/// Render the single-file regression trend dashboard HTML.
pub fn render_trend_html(runs: &[RunRecord], stats: &[ScenarioTrend]) -> String {
    let mut run_rows = String::new();
    for r in runs {
        let total = r.passed + r.failed;
        let pct = (r.passed * 100).checked_div(total).unwrap_or(0) as u32;
        run_rows.push_str("<tr><td><code>");
        run_rows.push_str(&esc(&r.run_id));
        run_rows.push_str("</code></td><td>");
        run_rows.push_str(&esc(&r.timestamp));
        run_rows.push_str("</td><td>");
        run_rows.push_str(&esc(r.branch.as_deref().unwrap_or("unknown")));
        run_rows.push_str("</td><td><span class=\"bar\"><span style=\"width:");
        run_rows.push_str(&pct.to_string());
        run_rows.push_str("%\"></span></span> ");
        run_rows.push_str(&r.passed.to_string());
        run_rows.push_str("P / ");
        run_rows.push_str(&r.failed.to_string());
        run_rows.push_str("F</td><td>");
        run_rows.push_str(&pct.to_string());
        run_rows.push_str("%</td><td><a href=\"trace.html?run=");
        run_rows.push_str(&esc(&r.run_id));
        run_rows.push_str("\">trace</a></td></tr>");
    }

    let mut scen_rows = String::new();
    for s in stats {
        let rate = (s.pass_rate() * 100.0).round() as u32;
        scen_rows.push_str("<tr><td><code>");
        scen_rows.push_str(&esc(&s.scenario_id));
        scen_rows.push_str("</code></td><td>");
        scen_rows.push_str(&esc(&s.name));
        scen_rows.push_str("</td><td>");
        scen_rows.push_str(&s.runs.to_string());
        scen_rows.push_str("</td><td>");
        scen_rows.push_str(&s.passes.to_string());
        scen_rows.push_str("</td><td>");
        scen_rows.push_str(&s.fails.to_string());
        scen_rows.push_str("</td><td>");
        scen_rows.push_str(&s.skips.to_string());
        scen_rows.push_str("</td><td>");
        scen_rows.push_str(&rate.to_string());
        scen_rows.push_str("%</td><td>");
        if s.is_flaky() {
            scen_rows.push_str("<span class=\"flaky-badge\">flaky</span>");
        } else if s.pass_rate() >= 1.0 {
            scen_rows.push_str("<span class=\"chip chip-pass\">stable-pass</span>");
        } else if s.runs > 0 {
            scen_rows.push_str("<span class=\"chip chip-fail\">failing</span>");
        } else {
            scen_rows.push_str("<span class=\"chip chip-skip\">no data</span>");
        }
        scen_rows.push_str("</td></tr>");
    }

    TREND_TEMPLATE
        .replace("__RUNS__", &runs.len().to_string())
        .replace("__RUN_ROWS__", &run_rows)
        .replace("__SCEN_ROWS__", &scen_rows)
}

/// Serialize a value for inline embedding inside a `<script type="application/json">`
/// block. `<`, `>` and `&` are escaped so the payload can never terminate the
/// script tag or inject markup, while remaining valid JSON.
pub fn embed_json<T: Serialize + ?Sized>(value: &T) -> String {
    let raw = serde_json::to_string(value).unwrap_or_else(|_| "{}".to_string());
    raw.replace('<', "\\u003c")
        .replace('>', "\\u003e")
        .replace('&', "\\u0026")
}

/// Escape a string for direct interpolation into HTML text/attributes.
pub fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}

fn status_class(status: &str) -> &'static str {
    match status {
        "PASS" => "pass",
        "FAIL" => "fail",
        _ => "skip",
    }
}

