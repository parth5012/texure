    fn fixture_runs(n: usize) -> Vec<RunRecord> {
        (0..n)
            .map(|i| RunRecord {
                run_id: format!("run_2026111{i}_00000{i}"),
                timestamp: format!("2026-11-1{}T10:00:{:02}+00:00", i % 9, i),
                app_version_name: None,
                build_hash: Some("abc1234".to_string()),
                branch: Some("main".to_string()),
                total_scenarios: 2,
                passed: if i == 1 { 1 } else { 2 },
                failed: if i == 1 { 1 } else { 0 },
                duration_ms: 900 + i as u64,
            })
            .collect()
    }

