    #[test]
    fn test_trace_html_escapes_html_in_payloads() {
        let (mut run, mut scenarios, mut steps) = fixture_run();
        run.branch = Some("main</script><script>alert(1)</script>".to_string());
        scenarios[0].name = "<img src=x onerror=alert(1)>".to_string();
        steps[0].result_json =
            Some(r#"{"rev":7,"nodes":[{"text":"<script>evil()</script>"}]}"#.to_string());

        let html = render_trace_html(&run, &scenarios, &steps);

        // No raw injection survives in the document
        assert!(
            !html.contains("<script>alert(1)"),
            "unescaped script payload"
        );
        assert!(!html.contains("<img src=x"), "unescaped img payload");
        // Escaped forms are present
        assert!(
            html.contains("&lt;img"),
            "html-escaped scenario name missing"
        );
        assert!(html.contains("\\u003c"), "json-escaped payload missing");
    }

